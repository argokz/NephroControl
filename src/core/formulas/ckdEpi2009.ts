// CKD-EPI 2009 [И1], мл/мин/1,73 м² — основная формула, по ней определяется стадия ХБП.
//
// eGFR = 141 × min(Scr/κ, 1)^α × max(Scr/κ, 1)^(−1,209) × 0,993^возраст × 1,018 [ж]
// κ = 0,7 (ж) / 0,9 (м); α = −0,329 (ж) / −0,411 (м)
//
// Реализована общая формула. Упрощённая таблица из текста [И1] не используется:
// в ней опечатки в строках для мужчин — множитель 144 вместо 141, «СКр/0,0» и «СКр/0,7»
// вместо «СКр/0,9» (сверено с официальным текстом [И1] 29.09.2026; см. README).
//
// Расовый коэффициент (× 1,159) из исходной публикации намеренно не реализован:
// по решению от 29.09.2026 он удалён (глобальная настройка применялась бы ко всем
// пациентам без признака расы; KDIGO 2024 [И8] от него отказывается). Это отступление
// от ТЗ (раздел 5.1) описано в README.

import type { Sex } from '../types';

export function ckdEpi2009(scrMgDl: number, ageYears: number, sex: Sex): number {
  const female = sex === 'female';
  const kappa = female ? 0.7 : 0.9;
  const alpha = female ? -0.329 : -0.411;
  const ratio = scrMgDl / kappa;
  return (
    141 *
    Math.min(ratio, 1) ** alpha *
    Math.max(ratio, 1) ** -1.209 *
    0.993 ** ageYears *
    (female ? 1.018 : 1)
  );
}
